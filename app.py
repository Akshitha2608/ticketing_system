@app.route('/tickets/<int:ticket_id>')
@login_required()
def ticket_detail(ticket_id):
    u=me(); t=get_ticket(ticket_id)
    if not t: abort(404)
    if not can_view(t,u): abort(403)
    with db() as conn:
        msgs=conn.execute('SELECT m.*,u.name sender FROM messages m JOIN users u ON u.id=m.sender_id WHERE ticket_id=%s AND (%s=TRUE OR internal=FALSE) ORDER BY m.id',(ticket_id,u['role']=='admin')).fetchall()
        hist=conn.execute('SELECT h.*,u.name actor FROM history h LEFT JOIN users u ON u.id=h.actor_id WHERE ticket_id=%s ORDER BY h.id DESC',(ticket_id,)).fetchall()
        files=conn.execute('SELECT id,name,created FROM attachments WHERE ticket_id=%s ORDER BY id',(ticket_id,)).fetchall()
    return render_template('ticket_detail.html',ticket=t,messages=msgs,history=hist,files=files)


@app.route('/tickets/<int:ticket_id>/attachments/<int:attachment_id>')
@login_required()
def download_attachment(ticket_id,attachment_id):
    u=me(); t=get_ticket(ticket_id)
